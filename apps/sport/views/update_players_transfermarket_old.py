"""
TransferMarket Player Data Update View
Updates existing Players with TransferMarket data while preserving Sportmonks data
"""
from django.http import JsonResponse
from django.views.decorators.csrf import csrf_exempt
from django.contrib.auth.decorators import login_required
from django.utils import timezone
from ..models import Players, Sport
import re
from decimal import Decimal


@csrf_exempt
@login_required
def AdminTransferMarketPlayersGetData(request):
    """
    Update Players model with TransferMarket data
    - Primary source: Sportmonks (for match/league integration)
    - Update source: TransferMarket (for detailed player info, market value, images)
    - Protected field: name_tr (manually added)
    """
    if request.method == "POST":
        sport_type = request.POST.get('sport', 'football')

        try:
            # Get sport
            sport = Sport.objects.filter(name__iexact=sport_type).first()
            if not sport:
                return JsonResponse({
                    'type': 'Error',
                    'message': f'Sport "{sport_type}" not found'
                })

            # Get players from the main Players model (not MultiSourcePlayers)
            players = Players.objects.filter(sport=sport).select_related('team')

            if not players.exists():
                return JsonResponse({
                    'type': 'Error',
                    'message': f'No players found for {sport_type}'
                })

            # Statistics
            stats = {
                'total': players.count(),
                'updated': 0,
                'matched': 0,
                'failed': 0,
                'errors': []
            }

            # Process each player
            for player in players:
                try:
                    # Get TransferMarket data for this player
                    tm_data = get_transfermarket_data_for_player(player)

                    if tm_data:
                        # Update player with TransferMarket data
                        update_player_with_transfermarket_data(player, tm_data)
                        stats['updated'] += 1
                        stats['matched'] += 1
                    else:
                        stats['failed'] += 1

                except Exception as e:
                    stats['failed'] += 1
                    stats['errors'].append(f"Error updating {player.name}: {str(e)}")

            success_message = (
                f"TransferMarket update completed. "
                f"Total: {stats['total']}, "
                f"Updated: {stats['updated']}, "
                f"Matched: {stats['matched']}, "
                f"Failed: {stats['failed']}"
            )

            if stats['errors']:
                success_message += f". Errors: {len(stats['errors'])}"

            return JsonResponse({
                'type': 'Success',
                'message': success_message,
                'stats': stats
            })

        except Exception as e:
            return JsonResponse({
                'type': 'Error',
                'message': f'Error processing TransferMarket data: {str(e)}'
            })

    return JsonResponse({'type': 'Error', 'message': 'Invalid request method.'})


def get_transfermarket_data_for_player(player):
    """
    Get TransferMarket data for a specific player

    This function should integrate with your existing scraping system.
    Options:
    1. Read from scraped JSON files
    2. Query a database table with scraped data
    3. Trigger a targeted scrape
    4. Use an API if available

    Returns TransferMarket data dict or None if not found
    """

    # Method 1: If you have TransferMarket data in a file/database, read it
    # Example: Read from a JSON file generated by your Scrapy spider
    tm_data = None

    # Try to match by existing transfermarkt_id
    if player.transfermarkt_id:
        tm_data = find_tm_data_by_id(player.transfermarkt_id)
        if tm_data:
            return tm_data

    # Try to match by player name and team
    if player.name and player.team:
        tm_data = find_tm_data_by_name_and_team(player.name, player.team.name)
        if tm_data:
            return tm_data

    # Try to match by player name only (less reliable)
    if player.name:
        tm_data = find_tm_data_by_name(player.name)
        if tm_data:
            return tm_data

    return None


def find_tm_data_by_id(tm_id):
    """
    Find TransferMarket data by player ID
    """
    if not tm_id:
        return None

    tm_players = _get_cached_tm_data()

    for player in tm_players:
        if str(player.get('id', '')).strip() == str(tm_id).strip():
            return player

    return None


# Global cache for TransferMarket data
_tm_data_cache = None


def _get_cached_tm_data():
    """Get or load TransferMarket data with caching"""
    global _tm_data_cache
    if _tm_data_cache is None:
        _tm_data_cache = load_transfermarket_data()
    return _tm_data_cache


def find_tm_data_by_name_and_team(player_name, team_name):
    """
    Find TransferMarket data by player name and team
    More accurate matching using cached data
    """
    from difflib import SequenceMatcher

    tm_players = _get_cached_tm_data()

    best_match = None
    best_score = 0.0

    for tm_player in tm_players:
        # Calculate name similarity
        name_similarity = SequenceMatcher(
            None,
            player_name.lower().strip(),
            tm_player.get('name', '').lower().strip()
        ).ratio()

        # Calculate team similarity if available
        team_similarity = 0.0
        if 'current_club' in tm_player and tm_player['current_club']:
            team_similarity = SequenceMatcher(
                None,
                team_name.lower().strip(),
                tm_player['current_club'].get('name', '').lower().strip()
            ).ratio()

        # Combined score (70% name, 30% team)
        combined_score = (name_similarity * 0.7) + (team_similarity * 0.3)

        # Require minimum 80% match
        if combined_score > best_score and combined_score >= 0.80:
            best_score = combined_score
            best_match = tm_player

    return best_match


def find_tm_data_by_name(player_name):
    """
    Find TransferMarket data by player name only
    Less accurate - use as fallback, uses cached data
    """
    from difflib import SequenceMatcher

    tm_players = _get_cached_tm_data()

    best_match = None
    best_score = 0.0

    for tm_player in tm_players:
        similarity = SequenceMatcher(
            None,
            player_name.lower().strip(),
            tm_player.get('name', '').lower().strip()
        ).ratio()

        # Require minimum 85% match for name-only
        if similarity > best_score and similarity >= 0.85:
            best_score = similarity
            best_match = tm_player

    return best_match


def load_transfermarket_data():
    """
    Load TransferMarket data from your existing system

    Priority:
    1. Use existing MultiSourcePlayers with TransferMarket data
    2. Check for cached JSON file
    3. Fall back to empty list

    Returns: List of TransferMarket player dictionaries
    """
    import os
    import json
    from django.conf import settings

    try:
        # Method 1: Get from existing MultiSourcePlayers with TransferMarket data
        from ..models.multi_source_players import MultiSourcePlayers

        multi_source_players = MultiSourcePlayers.objects.filter(
            transfermarkt_id__isnull=False
        ).exclude(transfermarkt_id='').values(
            'transfermarkt_id',
            'name',
            'image_url',
            'current_market_value',
            'highest_market_value',
            'height',
            'weight',
            'age',
            'position',
            'foot',
            'citizenship',
            'joined',
            'contract_expires',
            'player_agent_name',
            'outfitter',
            'current_club_name',
            'place_of_birth_city',
            'place_of_birth_country'
        )

        if multi_source_players.exists():
            data = []
            for player in multi_source_players:
                tm_player = {
                    'id': player.get('transfermarkt_id'),
                    'name': player.get('name'),
                    'image_url': player.get('image_url'),
                    'current_market_value': player.get('current_market_value'),
                    'highest_market_value': player.get('highest_market_value'),
                    'height': player.get('height'),
                    'weight': player.get('weight'),
                    'age': player.get('age'),
                    'position': player.get('position'),
                    'foot': player.get('foot'),
                    'citizenship': player.get('citizenship'),
                    'joined': player.get('joined'),
                    'contract_expires': player.get('contract_expires'),
                    'player_agent': {'name': player.get('player_agent_name')} if player.get('player_agent_name') else None,
                    'outfitter': player.get('outfitter'),
                    'current_club': {'name': player.get('current_club_name')} if player.get('current_club_name') else None,
                    'place_of_birth': {
                        'city': player.get('place_of_birth_city'),
                        'country': player.get('place_of_birth_country')
                    }
                }
                data.append(tm_player)

            if data:
                print(f"[TM] Loaded {len(data)} players from MultiSourcePlayers")
                return data
    except Exception as e:
        print(f"[TM] Error loading from MultiSourcePlayers: {e}")

    # Method 2: Check for cached JSON file
    try:
        json_cache_path = os.path.join(settings.BASE_DIR, 'scraped_data', 'transfermarket_players_cache.json')
        if os.path.exists(json_cache_path):
            with open(json_cache_path, 'r', encoding='utf-8') as f:
                data = json.load(f)
                print(f"[TM] Loaded {len(data)} players from cache file")
                return data
    except Exception as e:
        print(f"[TM] Error loading from cache: {e}")

    print("[TM] No TransferMarket data available - check MultiSourcePlayers model or create cache file")
    return []


def update_player_with_transfermarket_data(player, tm_data):
    """
    Update a Player instance with TransferMarket data

    Rules:
    - DO NOT update: name_tr (manually maintained)
    - DO NOT update: api_id, team, league (from Sportmonks)
    - DO update: name, image, market value, physical stats, contract info
    """

    # Extract TransferMarket ID from URL if not already set
    if not player.transfermarkt_id and tm_data.get('href'):
        match = re.search(r'/spieler/(\d+)', tm_data['href'])
        if match:
            player.transfermarkt_id = match.group(1)

    if tm_data.get('href'):
        # Build full URL if only path provided
        if tm_data['href'].startswith('/'):
            player.transfermarkt_url = f"https://www.transfermarkt.com{tm_data['href']}"
        else:
            player.transfermarkt_url = tm_data['href']

    # Update name (but NOT name_tr)
    if tm_data.get('name') and not player.name:
        player.name = tm_data['name']

    # Update display name
    if tm_data.get('display_name'):
        player.display_name = tm_data['display_name']

    # Update last name
    if tm_data.get('last_name'):
        player.last_name = tm_data['last_name']

    # Update first name
    if tm_data.get('first_name'):
        player.first_name = tm_data['first_name']

    # Update image URLs
    if tm_data.get('image_url'):
        player.image_url = tm_data['image_url']
        # If no other image exists, use this as image_path
        if not player.image_path and not player.image:
            player.image_path = tm_data['image_url']

    # Update physical attributes
    if tm_data.get('height'):
        player.height = tm_data['height']

    if tm_data.get('weight'):
        player.weight = tm_data['weight']

    if tm_data.get('age'):
        player.age = tm_data['age']

    if tm_data.get('birthdate') or tm_data.get('date_of_birth'):
        player.birthdate = tm_data.get('birthdate') or tm_data.get('date_of_birth')

    # Update birthplace
    if tm_data.get('place_of_birth'):
        if isinstance(tm_data['place_of_birth'], dict):
            player.place_of_birth_city = tm_data['place_of_birth'].get('city')
            player.place_of_birth_country = tm_data['place_of_birth'].get('country')
        else:
            player.birthplace = str(tm_data['place_of_birth'])

    # Update citizenship/nationality
    if tm_data.get('citizenship'):
        player.citizenship = tm_data['citizenship']

    # Update position info
    if tm_data.get('position'):
        # Map TransferMarket position to your Position_List choices
        player.position = map_position_to_choices(tm_data['position'])

    if tm_data.get('detailed_position'):
        player.detailed_position = map_position_to_choices(tm_data['detailed_position'])

    # Update jersey number
    if tm_data.get('number'):
        player.number = str(tm_data['number'])

    # Update foot preference
    if tm_data.get('foot'):
        player.foot = tm_data['foot']

    # Update market value (IMPORTANT for TransferMarket)
    if tm_data.get('current_market_value'):
        player.current_market_value = tm_data['current_market_value']
        # Parse numeric value
        parse_market_value(player, tm_data['current_market_value'])
        player.market_value_last_updated = timezone.now()

    if tm_data.get('highest_market_value'):
        player.highest_market_value = tm_data['highest_market_value']

    # Update contract information
    if tm_data.get('joined'):
        player.joined = tm_data['joined']

    if tm_data.get('contract_expires'):
        player.contract_expires = tm_data['contract_expires']

    # Update agent information
    if tm_data.get('player_agent'):
        if isinstance(tm_data['player_agent'], dict):
            player.player_agent_name = tm_data['player_agent'].get('name')
        else:
            player.player_agent_name = str(tm_data['player_agent'])

    # Update outfitter/sponsor
    if tm_data.get('outfitter'):
        player.outfitter = tm_data['outfitter']

    # Save the updated player
    player.save()


def map_position_to_choices(tm_position):
    """
    Map TransferMarket position names to your Position_List choices
    Adjust this based on your Position_List in modelHelper.py
    """
    position_mapping = {
        'goalkeeper': 'Goalkeeper',
        'centre-back': 'Defender',
        'left-back': 'Defender',
        'right-back': 'Defender',
        'defensive midfield': 'Midfielder',
        'central midfield': 'Midfielder',
        'attacking midfield': 'Midfielder',
        'left midfield': 'Midfielder',
        'right midfield': 'Midfielder',
        'left winger': 'Forward',
        'right winger': 'Forward',
        'centre-forward': 'Forward',
        'second striker': 'Forward',
    }

    tm_pos_lower = tm_position.lower().strip()
    return position_mapping.get(tm_pos_lower, 'Midfielder')  # Default to Midfielder


def parse_market_value(player, value_str):
    """
    Parse market value string to extract numeric value and currency
    Examples: "€50.00m", "$25.5M", "£30m", "€1.2bn"
    """
    if not value_str:
        return

    import re

    value_str = value_str.strip()

    # Extract currency, number, and multiplier
    pattern = r'([€$£¥])?([\d,.]+)([kmb])?'
    match = re.search(pattern, value_str.lower())

    if match:
        currency_symbol, number_str, multiplier = match.groups()

        # Map currency symbol to code
        currency_map = {
            '€': 'EUR',
            '$': 'USD',
            '£': 'GBP',
            '¥': 'JPY'
        }

        if currency_symbol:
            player.market_value_currency = currency_map.get(currency_symbol, 'EUR')
        elif not player.market_value_currency:
            player.market_value_currency = 'EUR'  # Default

        # Parse numeric value
        try:
            number = float(number_str.replace(',', ''))

            # Apply multiplier
            if multiplier == 'k':
                number *= 1000
            elif multiplier == 'm':
                number *= 1000000
            elif multiplier == 'b':
                number *= 1000000000

            player.market_value_numeric = Decimal(str(number))

        except (ValueError, TypeError):
            pass


@csrf_exempt
@login_required
def SearchTransferMarketPlayer(request):
    """
    Search for a specific player on TransferMarket and update
    More accurate matching by providing search criteria
    """
    if request.method == "POST":
        player_id = request.POST.get('player_id')
        search_name = request.POST.get('search_name')
        search_team = request.POST.get('search_team')

        try:
            player = Players.objects.get(id=player_id)

            # Use provided search terms or player's existing data
            name = search_name or player.name
            team = search_team or (player.team.name if player.team else None)

            # Search TransferMarket with specific criteria
            tm_data = find_tm_data_by_name_and_team(name, team) if team else find_tm_data_by_name(name)

            if tm_data:
                update_player_with_transfermarket_data(player, tm_data)
                return JsonResponse({
                    'type': 'Success',
                    'message': f'Player {player.name} updated with TransferMarket data'
                })
            else:
                return JsonResponse({
                    'type': 'Error',
                    'message': f'No TransferMarket data found for {name}'
                })

        except Players.DoesNotExist:
            return JsonResponse({
                'type': 'Error',
                'message': 'Player not found'
            })
        except Exception as e:
            return JsonResponse({
                'type': 'Error',
                'message': f'Error: {str(e)}'
            })

    return JsonResponse({'type': 'Error', 'message': 'Invalid request method.'})

